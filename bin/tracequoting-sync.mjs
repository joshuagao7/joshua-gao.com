#!/usr/bin/env node
// Bring the Force Platform trace viewer into this site, encrypted.
//
//   node bin/tracequoting-sync.mjs [path/to/Hardware/traces/viewer]
//
// Reads the viewer (index.html + dxf.js), its manifest, the layers that are in the
// Rev 2.2 stack (plus the day-one originals and the conductive layers' webbed
// outlines), and writes them under lib/tracequoting/data/ as TypeScript modules
// holding AES-256-GCM ciphertext (key: TRACEQUOTING_DATA_KEY in .env.local). Nothing
// readable is written into the repository. The site decrypts per request, behind the
// password gate, in app/api/tracequoting/.
import { createCipheriv, randomBytes } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync, existsSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const src = resolve(process.argv[2] || join(root, '..', 'Hardware', 'traces', 'viewer'))
const out = join(root, 'lib', 'tracequoting', 'data')

// key from the environment, else from .env.local, so the script works from a shell
let hex = process.env.TRACEQUOTING_DATA_KEY || ''
if (!hex && existsSync(join(root, '.env.local'))) {
  const m = readFileSync(join(root, '.env.local'), 'utf8').match(/^TRACEQUOTING_DATA_KEY=([0-9a-f]{64})/m)
  if (m) hex = m[1]
}
if (!/^[0-9a-f]{64}$/i.test(hex)) {
  console.error('TRACEQUOTING_DATA_KEY missing: 64 hex chars, in the environment or .env.local')
  process.exit(1)
}
const key = Buffer.from(hex, 'hex')

const encrypt = (buf) => {
  const iv = randomBytes(12)
  const c = createCipheriv('aes-256-gcm', key, iv)
  const ct = Buffer.concat([c.update(buf), c.final()])
  return Buffer.concat([iv, c.getAuthTag(), ct]).toString('base64')
}
const modName = (name) => 'f_' + name.replace(/[^A-Za-z0-9]+/g, '_')

const manifest = JSON.parse(readFileSync(join(src, 'manifest.json'), 'utf8'))
const stack = manifest.layers.filter((L) => L.stack != null).sort((a, b) => a.stack - b.stack)
if (!stack.length) { console.error('manifest has no stack layers -- run tools/export_rev.py first'); process.exit(1) }
// plus the day-one originals (the drawings as first supplied), which the viewer lists
// under its own "Original designs" dropdown for overlay checks
const originals = manifest.layers.filter((L) => L.stack == null && L.kind === 'original' && !L.variantOf)
const ship = [...stack, ...originals]

// the viewer, with dxf.js inlined so one document is served
let html = readFileSync(join(src, 'index.html'), 'utf8')
const dxf = readFileSync(join(src, 'dxf.js'), 'utf8')
if (!html.includes('<script src="dxf.js"></script>')) { console.error('index.html: no dxf.js tag'); process.exit(1) }
html = html.replace('<script src="dxf.js"></script>', '<script>\n' + dxf.replace(/<\/script/g, '<\\/script') + '\n</script>')

mkdirSync(out, { recursive: true })
for (const f of readdirSync(out)) unlinkSync(join(out, f))

const files = []
const put = (name, buf, kind) => {
  const mod = modName(name)
  writeFileSync(join(out, mod + '.ts'), `// ${kind}: ${name} -- AES-256-GCM, see bin/tracequoting-sync.mjs\nexport const enc = ${JSON.stringify(encrypt(buf))}\n`)
  files.push({ name, mod, bytes: buf.length })
}
put('index.html', Buffer.from(html, 'utf8'), 'viewer')
const site = { ...manifest, layers: ship }
put('manifest.json', Buffer.from(JSON.stringify(site), 'utf8'), 'manifest')
for (const L of ship) {
  put(L.file, readFileSync(join(src, L.file)), 'layer')
  // the webbed outline (part + webbing bars unioned) a conductive layer's Download
  // swaps in when the Webbing switch is on; fetched by the viewer only then
  if (L.dxf?.web?.file) put(L.dxf.web.file, readFileSync(join(src, L.dxf.web.file)), 'webbed outline')
}

writeFileSync(join(out, 'index.ts'),
  `// generated by bin/tracequoting-sync.mjs -- do not edit\n` +
  `const files: Record<string, () => Promise<{ enc: string }>> = {\n` +
  files.map((f) => `  ${JSON.stringify(f.name)}: () => import('./${f.mod}'),`).join('\n') +
  `\n}\nexport default files\n`)

console.log(`tracequoting-sync: ${files.length} files from ${src}`)
for (const f of files) console.log(`  ${(f.bytes / 1024).toFixed(0).padStart(6)} KB  ${f.name}`)
